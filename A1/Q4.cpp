#include <iostream>
using namespace std;

int main() {
    cout << "Size of char\t\t: " << sizeof(char) << " byte(s)\n";
    cout << "Size of short\t\t: " << sizeof(short) << " byte(s)\n";
    cout << "Size of int\t\t: " << sizeof(int) << " byte(s)\n";
    cout << "Size of long\t\t: " << sizeof(long) << " byte(s)\n";
    cout << "Size of long long\t: " << sizeof(long long) << " byte(s)\n";
    cout << "Size of float\t\t: " << sizeof(float) << " byte(s)\n";
    cout << "Size of double\t\t: " << sizeof(double) << " byte(s)\n";
    cout << "Size of long double\t: " << sizeof(long double) << " byte(s)\n";

    return 0;
}
